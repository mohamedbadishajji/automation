def export_jsonl(tenders: List[Tender], path: str) -> int:
    relevant = [t for t in tenders if t.is_it_relevant]
    if not relevant:
        return 0
    with open(path, "a", encoding="utf-8") as f:
        for t in relevant:
            f.write(json.dumps(asdict(t), ensure_ascii=False) + "\n")
    return len(relevant)


def main():
    store = TenderStore(CONFIG["db_path"])

    all_new: List[Tender] = []
    if CONFIG["enable_haicop"]:
        all_new += run_haicop_scraper(store)
    else:
        log.info("HAICOP source disabled (CONFIG['enable_haicop'] = False) - skipping.")

    if CONFIG["enable_wmc"]:
        all_new += run_wmc_scraper(store)
    else:
        log.info("WebManagerCenter source disabled (CONFIG['enable_wmc'] = False) - skipping.")

    exported = export_jsonl(all_new, CONFIG["jsonl_path"])

    log.info("=" * 70)
    log.info(f"Run complete: {len(all_new)} new tenders discovered, "
              f"{exported} passed the OliveSoft software-relevance filter "
              f"(threshold={CONFIG['export_relevance_threshold']}).")
    log.info(f"Database totals: {store.stats()}")
    if exported:
        log.info(f"Relevant tenders appended to: {CONFIG['jsonl_path']}")
    return all_new


if __name__ == "__main__":
    main()