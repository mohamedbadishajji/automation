HAICOP_TENDER_LINK_RE = re.compile(r"/fr/appels-doffres/(Tender-(\d+))")


def haicop_discover_recent_ids() -> List[int]:
    html = fetch(CONFIG["haicop_home"])
    if not html:
        return []
    return sorted({int(m.group(2)) for m in HAICOP_TENDER_LINK_RE.finditer(html)}, reverse=True)


def haicop_resolve_title(full_text: str, tender_id: str) -> str:
    """Prefer "Objet" as the title, but fall back to "Descriptif" when
    "Objet" is missing or too short to be an informative title.

    Verified live: Tender-96634's "Objet" is the internal reference code
    "tma systeme AMEN" (16 chars), while its "Descriptif" is the real,
    actionable description ("maintenance applicatives du Systeme
    d'information Amen Social du MAS"). Falling back keeps the export
    usable for tenders that follow this pattern, without discarding
    "Objet" for the (more common) tenders where it's already descriptive
    (e.g. Tender-103899's Objet: "Acquisition de materiel roulant")."""
    objet = extract_label_value(full_text, "Objet")
    descriptif = extract_label_value(full_text, "Descriptif")
    if objet and len(objet) >= CONFIG["min_title_length"]:
        return objet
    if descriptif:
        return descriptif
    return objet or f"Tender {tender_id}"


def haicop_parse_tender(full_text: str, tender_id: str, url: str) -> Optional[Tender]:
    full_text = _normalize_for_matching(full_text)
    if "Numéro A.O" not in full_text:
        return None

    title = haicop_resolve_title(full_text, tender_id)
    text = scope_to_detail_block(full_text)
    org = extract_label_value(text, "Acheteur public")
    domain_type = extract_label_value(text, "Type de commande")
    region = extract_label_value(text, "Région d'exécution")

    deadline = extract_label_value(text, "Date limite de réception des offres")
    if not looks_like_date(deadline):
        deadline = ""
    published = extract_label_value(text, "Date de publication")
    if not looks_like_date(published):
        published = ""

    budget = parse_amount(extract_label_value(text, "Montant du cautionnement provisoire") or "")

    is_relevant, score, reasons = classify_haicop_relevance(title, domain_type)

    return Tender(
        source="HAICOP", external_id=tender_id, title=title or f"Tender {tender_id}",
        organization=org, domain_type=domain_type, published_date=published,
        deadline=deadline, budget=budget, region=region, url=url,
        raw_excerpt=text[:500], is_it_relevant=is_relevant, confidence_score=score,
        relevance_reasons="; ".join(reasons),
    )


def run_haicop_scraper(store: TenderStore) -> List[Tender]:
    log.info("HAICOP: discovering recent tender IDs from the homepage widget ...")
    recent_ids = haicop_discover_recent_ids()
    if not recent_ids:
        log.warning("HAICOP: no IDs discovered - site may be unreachable or its layout changed.")
        return []

    newest = max(recent_ids)
    window = range(newest, max(newest - CONFIG["haicop_id_backfill"], 0), -1)
    log.info(f"HAICOP: newest ID={newest}, scanning {CONFIG['haicop_id_backfill']} IDs backward")

    new_tenders = []
    skipped_known = 0
    for tid in window:
        ext_id = f"Tender-{tid}"
        if store.seen_external_id("HAICOP", ext_id):
            skipped_known += 1
            continue
        url = CONFIG["haicop_tender_url_tpl"].format(id=tid)
        html = fetch(url)
        if not html:
            continue
        text = BeautifulSoup(html, "html.parser").get_text("\n")
        tender = haicop_parse_tender(text, ext_id, url)
        if tender and store.upsert(tender):
            new_tenders.append(tender)
            flag = "IT-relevant" if tender.is_it_relevant else "other"
            log.info(f"  + new [{ext_id}] ({flag}, score={tender.confidence_score}) {tender.title[:60]}")
    if skipped_known:
        log.info(f"HAICOP: skipped {skipped_known} already-known IDs without a network call")
    return new_tenders


