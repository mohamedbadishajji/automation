def fetch(url: str) -> Optional[str]:
    for attempt in range(CONFIG["max_retries"] + 1):
        try:
            resp = SESSION.get(url, timeout=CONFIG["request_timeout"])
            time.sleep(CONFIG["request_delay_seconds"])
            if resp.status_code == 404:
                return None
            resp.raise_for_status()
            resp.encoding = resp.apparent_encoding
            return resp.text
        except requests.RequestException as e:
            log.warning(f"Attempt {attempt + 1} failed for {url}: {e}")
            time.sleep(2 * (attempt + 1))
    log.error(f"Giving up on {url}")
    return None


def _normalize_for_matching(text: str) -> str:
    """French sometimes hyphenates or spaces out a compound that our
    keyword list expects solid ('plate-forme'/'plate forme' for
    'plateforme') - a real HAICOP tender ("acquisition des licences pour
    le site de plateforme TUNEPS...") was missed in one run only because
    of this. Normalize the known variants before matching.

    Also normalizes typographic (curly) apostrophes to plain ASCII ones.
    Verified live on marchespublics.gov.tn: the same field label renders
    with a curly apostrophe (Région d'exécution, U+2019) in a single-lot
    tender's top-level template, but with a plain ASCII apostrophe when
    the same label appears inside a per-lot "LotN" block on a multi-lot
    tender. A label constant hardcoded with only one style would silently
    return "" on pages using the other."""
    text = text.replace("\u2019", "'").replace("\u2018", "'")
    return re.sub(r"plate[\s-]forme", "plateforme", text, flags=re.I)


def _keyword_hits(text: str, keywords: List[str]) -> List[str]:
    text_l = _normalize_for_matching(text).lower()
    hits = []
    for kw in keywords:
        pattern = r"\b" + re.escape(kw.lower()) + r"\w*"
        if re.search(pattern, text_l):
            hits.append(kw)
    return hits


def looks_like_tender(text: str) -> bool:
    return bool(_keyword_hits(text, CONFIG["tender_signal_phrases"]))


def classify_software_relevance(text: str) -> Tuple[bool, float, List[str]]:
    """A tender is only flagged relevant if it BOTH looks like an actual
    tender/procurement notice AND mentions something in OliveSoft's
    domain - mentioning 'intelligence artificielle' in a news op-ed is
    not a lead."""
    if not looks_like_tender(text):
        return False, 0.0, []
    hits = _keyword_hits(text, CONFIG["software_keywords"])
    score = round(min(1.0, 0.2 * len(hits)), 2)
    return bool(hits), score, hits


def classify_haicop_relevance(title: str, domain_type: str) -> Tuple[bool, float, List[str]]:
    dt_l = domain_type.lower()
    reasons = []
    score = 0.0

    is_hardware_only = any(h in dt_l for h in CONFIG["haicop_hardware_only_hints"])
    is_software_category = any(h in dt_l for h in CONFIG["haicop_software_category_hints"])

    if is_software_category and not is_hardware_only:
        score += 0.6
        reasons.append(f"category:{domain_type}")
    elif is_hardware_only:
        score += 0.1
        reasons.append(f"hardware-only-category:{domain_type}")

    title_hits = _keyword_hits(title, CONFIG["software_keywords"])
    if title_hits:
        score += min(0.4, 0.15 * len(title_hits))
        reasons.append("title:" + ",".join(title_hits))

    priority_hits = _keyword_hits(title, CONFIG["haicop_priority_expertise_hints"])
    if priority_hits:
        score += 0.2  # ranks BI/CRM/data-integration tenders above bare hardware buys
        reasons.append("olivesoft-expertise:" + ",".join(priority_hits))

    score = round(min(1.0, score), 2)
    return score >= CONFIG["export_relevance_threshold"], score, reasons


def extract_label_value(text: str, label: str) -> str:
    m = re.search(re.escape(label) + r"\s*:?\s*(.+)", text)
    if not m:
        return ""
    val = m.group(1).splitlines()[0].strip()[:300]
    if val.endswith(":") or val.lower().startswith(("date de", "numéro", "acheteur", "vous voulez")):
        return ""
    return val


def scope_to_detail_block(full_text: str) -> str:
    marker = "Numéro A.O"
    idx = full_text.find(marker)
    return full_text[idx:] if idx != -1 else full_text


def looks_like_date(value: str) -> bool:
    return bool(re.match(r"\d{2}-\d{2}-\d{4}", value))


def parse_amount(text: str) -> Optional[float]:
    m = re.search(r"[\d][\d\s]{2,}(?:[.,]\d+)?", text)
    if not m:
        return None
    try:
        return float(m.group(0).replace(" ", "").replace(",", "."))
    except ValueError:
        return None


def parse_french_date(text: str) -> Optional[datetime]:
    m = re.search(r"(\d{1,2})\s+(" + "|".join(FRENCH_MONTHS) + r")\s+(\d{4})", text.lower())
    if not m:
        return None
    day, month_name, year = m.groups()
    try:
        return datetime(int(year), FRENCH_MONTHS[month_name], int(day))
    except ValueError:
        return None


