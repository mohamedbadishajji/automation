WMC_ARTICLE_RE = re.compile(r"https://www\.webmanagercenter\.com/\d{4}/\d{2}/\d{2}/[^\s\"'<>]+")


def wmc_discover_links() -> List[str]:
    urls = []
    seen = set()

    for page in range(1, CONFIG["wmc_pages_to_scan"] + 1):
        html = fetch(CONFIG["wmc_listing_url_tpl"].format(page=page))
        if not html:
            break
        found = set(WMC_ARTICLE_RE.findall(html))
        if not found:
            break
        for href in found:
            if href not in seen:
                seen.add(href)
                urls.append(href)

    for kw in CONFIG["wmc_search_keywords"]:
        query = kw.replace("'", "%27").replace(" ", "+")
        html = fetch(CONFIG["wmc_search_url_tpl"].format(query=query))
        if not html:
            continue
        for href in set(WMC_ARTICLE_RE.findall(html)):
            if href not in seen:
                seen.add(href)
                urls.append(href)

    return urls


def _clean_wp_title(raw: str) -> str:
    # WordPress <title> tags are usually "Article Title - Site Name"
    return re.split(r"\s*[-–]\s*WebManagerCenter", raw, flags=re.I)[0].strip()


def wmc_parse_article(html: str, url: str) -> Optional[Tender]:
    soup = BeautifulSoup(html, "html.parser")

    h1 = soup.find("h1")
    if h1 and h1.get_text(strip=True):
        title = h1.get_text(strip=True)
    elif soup.title and soup.title.string:
        title = _clean_wp_title(soup.title.string)
    else:
        title = url.rstrip("/").split("/")[-1].replace("-", " ").capitalize()

    # Real article body: WordPress themes put story text in <p> tags; nav,
    # tag clouds and "related articles" widgets are lists/links, not prose.
    paragraphs = [p.get_text(" ", strip=True) for p in soup.find_all("p")]
    body_text = "\n".join(p for p in paragraphs if len(p) > 25)
    if not body_text:
        return None

    org_match = re.search(r"(?:[Ll]a société|[Ll]e|[Ll]a|[Ll]'|[Ll]’)\s+([A-ZÉÈÀ][\w'’\- ]{2,60})", body_text)
    organization = org_match.group(0).strip() if org_match else ""

    is_relevant, score, hits = classify_software_relevance(f"{title}\n{body_text}")
    pub_dt = parse_french_date(body_text[:200]) or parse_french_date(title)

    return Tender(
        source="WebManagerCenter", external_id=url.rstrip("/").split("/")[-1],
        title=title, organization=organization, domain_type="Annonce presse",
        published_date=pub_dt.strftime("%d-%m-%Y") if pub_dt else "",
        deadline="", budget=None, region="",
        url=url, raw_excerpt=body_text[:500], is_it_relevant=is_relevant,
        confidence_score=score, relevance_reasons=",".join(hits),
    ), pub_dt


def run_wmc_scraper(store: TenderStore) -> List[Tender]:
    log.info("WebManagerCenter: scanning archive + running OliveSoft keyword searches ...")
    urls = wmc_discover_links()
    if not urls:
        log.warning("WebManagerCenter: no links discovered - site may be unreachable or its layout changed.")
        return []

    cutoff = datetime.utcnow() - timedelta(days=CONFIG["wmc_max_age_days"])
    new_tenders = []
    for href in urls:
        html = fetch(href)
        if not html:
            continue
        parsed = wmc_parse_article(html, href)
        if not parsed:
            continue
        tender, pub_dt = parsed
        is_new = store.upsert(tender)
        if not is_new:
            continue
        if pub_dt and pub_dt < cutoff:
            log.info(f"  (stored, too old to export: {pub_dt.date()}) {tender.title[:60]}")
            continue
        new_tenders.append(tender)
        flag = "IT-relevant" if tender.is_it_relevant else "other"
        log.info(f"  + new ({flag}, score={tender.confidence_score}) {tender.title[:60]}")
    return new_tenders


