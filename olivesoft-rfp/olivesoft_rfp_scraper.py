class TenderStore:
    def __init__(self, db_path: str):
        self.conn = sqlite3.connect(db_path)
        self._init_schema()

    def _init_schema(self):
        self.conn.execute("""
            CREATE TABLE IF NOT EXISTS tenders (
                hash TEXT PRIMARY KEY,
                source TEXT, external_id TEXT, title TEXT, organization TEXT,
                domain_type TEXT, published_date TEXT, deadline TEXT,
                budget REAL, region TEXT, url TEXT, is_it_relevant INTEGER,
                confidence_score REAL, relevance_reasons TEXT, status TEXT,
                first_seen TEXT, last_seen TEXT
            )
        """)
        self.conn.execute("""
            CREATE TABLE IF NOT EXISTS events (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                tender_hash TEXT, event_type TEXT, timestamp TEXT
            )
        """)
        self.conn.commit()

    def upsert(self, t: Tender) -> bool:
        h = t.dedup_hash()
        now = datetime.utcnow().isoformat()
        is_new = self.conn.execute("SELECT 1 FROM tenders WHERE hash=?", (h,)).fetchone() is None
        if is_new:
            self.conn.execute(
                """INSERT INTO tenders (hash, source, external_id, title, organization,
                       domain_type, published_date, deadline, budget, region, url,
                       is_it_relevant, confidence_score, relevance_reasons, status,
                       first_seen, last_seen)
                   VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
                (h, t.source, t.external_id, t.title, t.organization, t.domain_type,
                 t.published_date, t.deadline, t.budget, t.region, t.url,
                 int(t.is_it_relevant), t.confidence_score, t.relevance_reasons,
                 "new", now, now),
            )
            self.conn.execute(
                "INSERT INTO events (tender_hash, event_type, timestamp) VALUES (?,?,?)",
                (h, "discovered", now),
            )
        else:
            self.conn.execute("UPDATE tenders SET last_seen=? WHERE hash=?", (now, h))
        self.conn.commit()
        return is_new

    def stats(self) -> dict:
        total, budget = self.conn.execute("SELECT COUNT(*), SUM(budget) FROM tenders").fetchone()
        it_relevant = self.conn.execute("SELECT COUNT(*) FROM tenders WHERE is_it_relevant=1").fetchone()[0]
        return {"total_tenders": total or 0, "total_budget_tnd": budget or 0.0, "it_relevant": it_relevant}

    def seen_external_id(self, source: str, external_id: str) -> bool:
        """Cheap pre-fetch check: a HAICOP Tender-<id> page's content never
        changes once published, so if we've already stored this exact
        (source, external_id) there is no point re-downloading and
        re-parsing it just to find out it's a duplicate. Skip the network
        call entirely instead."""
        row = self.conn.execute(
            "SELECT 1 FROM tenders WHERE source=? AND external_id=? LIMIT 1", (source, external_id)
        ).fetchone()
        return row is not None


