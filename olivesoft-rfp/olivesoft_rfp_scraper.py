@dataclass
class Tender:
    source: str
    external_id: str
    title: str
    organization: str = ""
    domain_type: str = ""
    published_date: str = ""
    deadline: str = ""
    budget: Optional[float] = None
    region: str = ""
    url: str = ""
    raw_excerpt: str = ""
    is_it_relevant: bool = False
    confidence_score: float = 0.0
    relevance_reasons: str = ""

    def dedup_hash(self) -> str:
        if self.source == "WebManagerCenter":
            # Free-text org extraction on WMC is a heuristic and can pull a
            # slightly different substring for two copies of the same
            # story (e.g. a republished/duplicate post), which would
            # otherwise defeat dedup. Title + publish date is a far more
            # stable identity for a news article than the org guess.
            date_key = self.published_date or re.search(r"/(\d{4}/\d{2}/\d{2})/", self.url).group(1) \
                if re.search(r"/(\d{4}/\d{2}/\d{2})/", self.url) else self.published_date
            key = f"{self.title.strip().lower()}|{self.source}|{date_key}"
        else:
            key = f"{self.title.strip().lower()}|{self.organization.strip().lower()}|{self.deadline}|{self.source}"
        return hashlib.md5(key.encode("utf-8")).hexdigest()


